import os
from pathlib import Path
import re
import subprocess

from scanner.models import Finding

DOCKERIGNORE_CONTENT = """# Auto-generated by secure-deploy to prevent secret leakage
.env
.env.*
.env*
*.secrets
.secrets_*
.git
*.pem
*.key
id_rsa
id_ed25519
terraform.tfstate*
node_modules
__pycache__
*.pyc
.DS_Store
*.log
credentials.json
service-account*.json
.htpasswd
"""

SECRET_ENV_ARG_PATTERN = re.compile(
    r"(?:SECRET|KEY|TOKEN|PASSWORD|PASSWD|AUTH|CREDENTIAL|PRIVATE)",
    re.IGNORECASE,
)


def sanitize_identifier(value: str) -> str:
    """Sanitize any string used in Docker tags or container names to [a-zA-Z0-9_.-]."""
    cleaned = re.sub(r"[^a-zA-Z0-9_.-]+", "-", value.strip().lower())
    # Collapse multiple hyphens or periods into a single hyphen
    cleaned = re.sub(r"[-]+", "-", cleaned)
    # Docker tags cannot start or end with period or dash
    cleaned = re.sub(r"^[-.]+", "", cleaned)
    cleaned = re.sub(r"[-.]+$", "", cleaned)
    return cleaned[:63] if cleaned else "app"


def lint_dockerfile(dockerfile_path: str) -> list[Finding]:
    """Lint a Dockerfile against DevSecOps best practices.

    Checks:
    - Running as root / no USER instruction (medium)
    - Secrets in ENV or ARG lines (high) -> Blocks deploy
    - ADD from remote URLs (medium)
    - "latest" base tag (low)
    - EXPOSE 22 (high) -> Blocks deploy
    """
    path = Path(dockerfile_path)
    if not path.exists():
        return []

    findings: list[Finding] = []
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()

    has_user_instruction = False

    for idx, line in enumerate(lines, start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue

        upper = stripped.upper()

        # Check FROM base tag
        if upper.startswith("FROM "):
            parts = stripped.split()
            if len(parts) >= 2:
                image_ref = parts[1].split()[0]
                if image_ref.endswith(":latest") or (":" not in image_ref and "@" not in image_ref and image_ref != "scratch"):
                    findings.append(
                        Finding(
                            file="Dockerfile",
                            line=idx,
                            type="docker_latest_tag",
                            severity="low",
                            masked_preview=f"[Dockerfile: 'latest' or untagged base image '{image_ref}']",
                        )
                    )

        # Check USER instruction
        if upper.startswith("USER "):
            user_val = stripped[5:].strip()
            if user_val in {"root", "0"}:
                findings.append(
                    Finding(
                        file="Dockerfile",
                        line=idx,
                        type="docker_root_user",
                        severity="medium",
                        masked_preview="[Dockerfile: explicit USER root detected]",
                    )
                )
            else:
                has_user_instruction = True

        # Check ENV / ARG for secrets
        if upper.startswith("ENV ") or upper.startswith("ARG "):
            directive = "ENV" if upper.startswith("ENV ") else "ARG"
            rest = stripped[4:].strip()
            if "=" in rest:
                var_name, var_val = rest.split("=", 1)
            else:
                tokens = rest.split(None, 1)
                var_name = tokens[0] if tokens else ""
                var_val = tokens[1] if len(tokens) > 1 else ""

            var_name = var_name.strip()
            var_val = var_val.strip()

            if SECRET_ENV_ARG_PATTERN.search(var_name) and var_val and var_val != '""' and var_val != "''":
                findings.append(
                    Finding(
                        file="Dockerfile",
                        line=idx,
                        type="docker_embedded_secret",
                        severity="high",
                        masked_preview=f"[Dockerfile: secret baked into {directive} '{var_name}']",
                    )
                )

        # Check ADD from remote URLs
        if upper.startswith("ADD "):
            rest = stripped[4:].strip()
            if rest.startswith("http://") or rest.startswith("https://") or " http://" in rest or " https://" in rest:
                findings.append(
                    Finding(
                        file="Dockerfile",
                        line=idx,
                        type="docker_remote_add",
                        severity="medium",
                        masked_preview="[Dockerfile: ADD instruction fetching from remote URL; prefer curl/wget with verification]",
                    )
                )

        # Check EXPOSE 22 (SSH)
        if upper.startswith("EXPOSE "):
            ports = stripped[7:].strip().split()
            if "22" in ports or "22/tcp" in ports:
                findings.append(
                    Finding(
                        file="Dockerfile",
                        line=idx,
                        type="docker_expose_ssh",
                        severity="high",
                        masked_preview="[Dockerfile: EXPOSE 22 (SSH service inside container is prohibited)]",
                    )
                )

    if not has_user_instruction:
        findings.append(
            Finding(
                file="Dockerfile",
                line=1,
                type="docker_no_user_instruction",
                severity="medium",
                masked_preview="[Dockerfile: Container runs as default root user; add a non-root USER]",
            )
        )

    return findings


def detect_stack(project_path: str) -> str:
    """Detect the application stack from project files (static, node, python, or unknown)."""
    root = Path(project_path)
    if (root / "package.json").exists():
        return "node"
    if (root / "requirements.txt").exists():
        return "python"
    if (root / "index.html").exists():
        return "static"
    return "unknown"


def generate_dockerfile(project_path: str) -> str:
    """Generate a hardened, non-root Dockerfile for detected project stack."""
    stack = detect_stack(project_path)
    if stack == "unknown":
        raise ValueError(
            "Unknown stack: project must contain package.json, requirements.txt, or index.html."
        )
    if stack == "static":
        return """FROM nginx:1.27-alpine
WORKDIR /usr/share/nginx/html
# Hardened Nginx configuration for static app
COPY . /usr/share/nginx/html/
# Create unprivileged runtime user
RUN touch /var/run/nginx.pid && \
    chown -R nginx:nginx /var/run/nginx.pid /var/cache/nginx /usr/share/nginx/html
USER nginx
EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
"""
    elif stack == "node":
        return """FROM node:20-alpine
WORKDIR /app
ENV NODE_ENV=production
# Add non-root system group and user
RUN addgroup -S appgroup && adduser -S appuser -G appgroup
COPY package*.json ./
RUN if [ -f package-lock.json ]; then npm ci --only=production; else npm install --only=production; fi
COPY . .
RUN chown -R appuser:appgroup /app
USER appuser
EXPOSE 3000
CMD ["npm", "start"]
"""
    elif stack == "python":
        return """FROM python:3.11-slim
WORKDIR /app
ENV PYTHONUNBUFFERED=1
# Create unprivileged app user
RUN useradd --create-home --shell /bin/bash appuser
COPY requirements.txt ./
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
RUN chown -R appuser:appuser /app
USER appuser
EXPOSE 8000
CMD ["python", "main.py"]
"""
    raise ValueError(f"Unsupported stack: {stack}")


def ensure_dockerignore(project_path: str) -> None:
    """Always create or ensure a strict .dockerignore exists in project root."""
    target = Path(project_path) / ".dockerignore"
    if not target.exists():
        target.write_text(DOCKERIGNORE_CONTENT, encoding="utf-8")
    else:
        existing = target.read_text(encoding="utf-8")
        append_rules = []
        for line in DOCKERIGNORE_CONTENT.splitlines():
            clean = line.strip()
            if clean and not clean.startswith("#") and clean not in existing:
                append_rules.append(clean)
        if append_rules:
            target.write_text(existing + "\n" + "\n".join(append_rules) + "\n", encoding="utf-8")


def run_docker_build(project_path: str, tag: str, timeout: int = 300) -> str:
    """Run docker build with argument list (never shell=True) and strict sanitization."""
    sanitized_tag = sanitize_identifier(tag.split(":")[0]) + ":" + sanitize_identifier(tag.split(":")[1])
    root = Path(project_path).resolve()

    # If no Dockerfile, generate one
    dockerfile = root / "Dockerfile"
    if not dockerfile.exists():
        content = generate_dockerfile(str(root))
        dockerfile.write_text(content, encoding="utf-8")

    ensure_dockerignore(str(root))

    cmd = ["docker", "build", "-t", sanitized_tag, "."]
    proc = subprocess.run(
        cmd,
        cwd=str(root),
        capture_output=True,
        text=True,
        timeout=timeout,
    )
    output = (proc.stdout or "") + "\n" + (proc.stderr or "")
    if proc.returncode != 0:
        raise RuntimeError(f"Docker build failed with code {proc.returncode}:\n{output}")
    return output
